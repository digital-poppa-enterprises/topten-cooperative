#!/usr/bin/env python3
"""
One-time setup: host the site's fonts locally instead of loading them from Google Fonts.

Run once, from anywhere, on a computer with internet access:

    python3 assets/fonts/localize-fonts.py

What it does
  1. Downloads Plus Jakarta Sans (weights 400, 500, 600, 700) and Material Symbols Outlined
     (the icon font) as .woff2 files into assets/fonts/.
  2. Writes the matching @font-face rules into assets/css/styles.css (between the
     LOCAL-FONTS:START / LOCAL-FONTS:END markers).
  3. Removes the Google Fonts <link> tags from the seven HTML pages.

It only needs Python 3 (standard library). Running it again is safe. After it finishes, open the
pages once with the internet disconnected to confirm the text and icons still look right.
"""
import os, re, sys, glob, urllib.request

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
FONT_DIR = os.path.join(ROOT, 'assets', 'fonts')
CSS_FILE = os.path.join(ROOT, 'assets', 'css', 'styles.css')

# The same two stylesheets the pages request from Google today.
BASE = os.environ.get('FONTS_BASE_URL', 'https://fonts.googleapis.com')
SOURCES = [
    ('plus-jakarta-sans', BASE + '/css2?family=Plus+Jakarta+Sans:wght@400;500;600;700&display=swap'),
    ('material-symbols-outlined', BASE + '/css2?family=Material+Symbols+Outlined:opsz,wght,FILL,GRAD@20..48,100..700,0..1,-50..200'),
]
# Google serves woff2 only to modern browsers, so identify as one.
UA = {'User-Agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Safari/537.36'}


def get(url):
    with urllib.request.urlopen(urllib.request.Request(url, headers=UA), timeout=30) as response:
        return response.read()


def build_font_face_css():
    os.makedirs(FONT_DIR, exist_ok=True)
    out, seen = [], {}
    for slug, css_url in SOURCES:
        css = get(css_url).decode('utf-8')
        blocks = re.findall(r'(?:/\*\s*([\w-]+)\s*\*/\s*)?(@font-face\s*\{[^}]*\})', css)
        if not blocks:
            sys.exit(f'No @font-face rules found for {slug}; Google may have changed its response.')
        for subset, block in blocks:
            url = re.search(r'url\(([^)]+)\)', block).group(1).strip('"\'')
            weight = re.search(r'font-weight:\s*([^;]+);', block).group(1).strip().replace(' ', '-')
            if url not in seen:
                name = '-'.join(p for p in (slug, weight, subset) if p) + '.woff2'
                with open(os.path.join(FONT_DIR, name), 'wb') as f:
                    f.write(get(url))
                seen[url] = name
                print('downloaded', name)
            block = re.sub(r'url\([^)]+\)', f'url("../fonts/{seen[url]}")', block)
            if 'font-display' not in block:
                block = block.rstrip('}').rstrip() + '\n  font-display: swap;\n}'
            out.append(f'/* {slug}{" / " + subset if subset else ""} */\n' + block)
    return '\n'.join(out)


def update_stylesheet(font_css):
    css = open(CSS_FILE, encoding='utf-8').read()
    pattern = re.compile(r'/\* LOCAL-FONTS:START.*?LOCAL-FONTS:END \*/', re.S)
    if not pattern.search(css):
        sys.exit('Markers not found in styles.css (was it edited?).')
    block = ('/* LOCAL-FONTS:START (generated by assets/fonts/localize-fonts.py) */\n'
             + font_css + '\n/* LOCAL-FONTS:END */')
    open(CSS_FILE, 'w', encoding='utf-8').write(pattern.sub(lambda m: block, css))


def update_pages():
    count = 0
    for page in glob.glob(os.path.join(ROOT, '*.html')):
        html = open(page, encoding='utf-8').read()
        new = re.sub(r'[ \t]*<!-- Fonts:[^>]*-->\n', '', html)
        new = re.sub(r'[ \t]*<link rel="preconnect" href="https://fonts\.(?:googleapis|gstatic)\.com"[^>]*>\n', '', new)
        new = re.sub(r'[ \t]*<link rel="stylesheet" href="https://fonts\.googleapis\.com/[^>]*>\n', '', new)
        if new != html:
            open(page, 'w', encoding='utf-8').write(new)
            count += 1
    return count


if __name__ == '__main__':
    css = build_font_face_css()
    update_stylesheet(css)
    print('Updated styles.css and', update_pages(), 'page(s).')
    print('Done. Fonts are now served from assets/fonts/.')
